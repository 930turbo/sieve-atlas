"""Generate the language catalog from the executable manifest."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]

def catalog():
    entries=json.loads((ROOT/'implementations.json').read_text(encoding='utf-8'))
    lines=['# Language catalog','','One baseline per language, then six additional variants. Paths link directly to the source. All commands below are run from the repository root using Python 3.10+. The runner invokes the real language toolchain, not a translation.','','## Baselines','','| Language | Source | Runtime / compiler | Storage | Run |','| --- | --- | --- | --- | --- |']
    for e in entries:
        if e['variant']!='classic': continue
        lines.append(f"| {e['language']} | [{Path(e['path']).name}](../{e['path']}) | {e['requires']} | {e['storage']} | `python tools/atlas.py run {e['id']} 100` |")
    lines+=['','## Variants','','| ID | Language | Approach | Source |','| --- | --- | --- | --- |']
    for e in entries:
        if e['variant']=='classic': continue
        lines.append(f"| `{e['id']}` | {e['language']} | {e['variant']} | [{Path(e['path']).name}](../{e['path']}) |")
    lines+=['','Run a variant the same way, for example `python tools/atlas.py run python-segmented 1000`.','','## Use a file directly','','```sh','python implementations/python/sieve.py 100','node implementations/javascript/sieve.mjs 100','runghc implementations/haskell/sieve.hs 100','gcc -std=c11 -O2 implementations/c/sieve.c -o sieve && ./sieve 100','g++ -std=c++17 -O2 implementations/cpp/sieve.cpp -o sieve && ./sieve 100','pwsh -NoProfile -File implementations/powershell/sieve.ps1 -Limit 100','```','','Build commands for every compiled entry live in [implementations.json](../implementations.json). Commands use GCC, G++, Mono, and other specific toolchain names; Windows users need the corresponding tools on PATH. The runner writes compiled output into `.build/<id>/`. OCaml may also create ignored `.cmi`/`.cmo` files beside the source.','','For reuse, copy the sieve function and its imports/types into your project. Python, JavaScript, TypeScript, Ruby, PHP, Perl, Lua, R, Julia, Nim, Bash, and PowerShell guard their command-line entry points. In the other standalone programs, remove the small main/driver section or adapt it into a module. C and C++ support `SIEVE_ATLAS_NO_MAIN`. This is a source reference library, not 30 separately packaged ecosystem libraries.','','Generated by `python tools/generate_docs.py`; edit the manifest to change this catalog.','']
    return '\n'.join(lines)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--check',action='store_true')
    a=p.parse_args()
    path=ROOT/'docs'/'LANGUAGES.md'
    content=catalog()
    if a.check:
        if not path.exists() or path.read_text(encoding='utf-8')!=content: raise SystemExit('Catalog is stale; run python tools/generate_docs.py')
        print('Language catalog is current')
    else: path.write_text(content,encoding='utf-8')

if __name__=='__main__': main()
